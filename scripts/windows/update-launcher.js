// Generate the small inline trust bootstrap before the first .ps1 is loaded.
// Hashes check release consistency; they are not a publisher signature.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = fileURLToPath(new URL("../../", import.meta.url));
const canonical = (text) => text.replace(/^\uFEFF/, "").replace(/\r\n/g, "\n");
const names = ["bootstrap.ps1", "console.ps1", "lifetime.ps1", "preview.ps1"];
const hashes = names.map(name => {
  const text = canonical(readFileSync(path.join(root, "scripts/windows", name), "utf8"));
  return `'${name}'='${createHash("sha256").update(text).digest("hex")}'`;
}).join(";");
const command = [
  "$ErrorActionPreference='Stop'",
  "try { $root=$env:BSIGN_LAUNCH_ROOT",
  `$expected=@{${hashes}}`,
  "$sha=[Security.Cryptography.SHA256]::Create()",
  "try { foreach($name in $expected.Keys) { $p=Join-Path $root ('scripts\\windows\\'+$name); $text=[IO.File]::ReadAllText($p,[Text.Encoding]::UTF8).Replace(([string][char]13+[char]10),[string][char]10); $actual=([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($text)))).Replace('-','').ToLowerInvariant(); if($actual -ne $expected[$name]){throw ('Launcher file changed or incomplete: '+$name+'. Download the version ZIP again.')} } } finally { $sha.Dispose() }",
  "foreach($name in $expected.Keys){ Unblock-File -LiteralPath (Join-Path $root ('scripts\\windows\\'+$name)) }",
  "if($env:BSIGN_LAUNCH_MODE -eq 'gui'){ & (Join-Path $root 'scripts\\windows\\preview.ps1') } elseif($env:BSIGN_LAUNCH_MODE -eq 'ui-test'){ & (Join-Path $root 'scripts\\windows\\preview.ps1') -UiSmokeTest } elseif($env:BSIGN_LAUNCH_MODE -eq 'smoke'){ & (Join-Path $root 'scripts\\windows\\console.ps1') -SmokeTest } else { & (Join-Path $root 'scripts\\windows\\console.ps1') }",
  "exit 0 } catch { Write-Host ('Preview launcher: '+$_.Exception.Message) -ForegroundColor Red; Write-Host 'If your organization requires signed scripts, contact IT. See START-HERE.html.'; exit 1 }",
].join("; ");
const output = `@echo off
setlocal DisableDelayedExpansion
cd /d "%~dp0"
title BSIGN TECH - Website Preview
rem Generated by scripts/windows/update-launcher.js. Checks only our four scripts.
set "BSIGN_LAUNCH_ROOT=%~dp0"
set "BSIGN_LAUNCH_MODE=console"
set "BSIGN_LAUNCH_PAUSE=1"
if /i "%~1"=="-SmokeTest" set "BSIGN_LAUNCH_MODE=smoke"
if /i "%~1"=="-Gui" set "BSIGN_LAUNCH_MODE=gui"
if /i "%~1"=="-UiSmokeTest" set "BSIGN_LAUNCH_MODE=ui-test"
if not "%~1"=="" set "BSIGN_LAUNCH_PAUSE=0"
powershell.exe -NoLogo -NoProfile -STA -ExecutionPolicy RemoteSigned -Command "${command}"
set "BSIGN_PREVIEW_EXIT=%ERRORLEVEL%"
if not "%BSIGN_PREVIEW_EXIT%"=="0" (
  echo.
  echo Preview could not start. See the message above or START-HERE.html.
  if "%BSIGN_LAUNCH_PAUSE%"=="1" pause
)
exit /b %BSIGN_PREVIEW_EXIT%
`;
if (command.length > 7000) throw Error("Launcher exceeds safe CMD command length");
const target = path.join(root, "START-WINDOWS.cmd");
if (process.argv.includes("--check")) {
  if (canonical(readFileSync(target, "utf8")) !== output) {
    console.error("Launcher hashes are stale. Run node scripts/windows/update-launcher.js");
    process.exitCode = 1;
  } else console.log("PASS: launcher hashes match all four scripts");
} else {
  writeFileSync(target, output);
  console.log("Updated START-WINDOWS.cmd with canonical script hashes");
}
